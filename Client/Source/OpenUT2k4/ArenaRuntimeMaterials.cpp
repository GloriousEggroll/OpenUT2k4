	double StatNum(const TSharedPtr<FJsonObject>& S, const TCHAR* Key, double Default)
	{
		return S.IsValid() ? Num(S->TryGetField(Key), Default) : Default;
	}

	// ---- name tests (matresolve LIGHTMAP_NAME / NON_COLOUR_NAME regexes) ----------------------

	/** (LM\d*$) : ends with "LM" followed by digits. */
	bool EndsWithLM(const FString& Name, bool bIgnoreCase)
	{
		int32 End = Name.Len();
		while (End > 0 && FChar::IsDigit(Name[End - 1])) { --End; }
		return End >= 2 && Name.Mid(End - 2, 2).Equals(TEXT("LM"), bIgnoreCase ? ESearchCase::IgnoreCase : ESearchCase::CaseSensitive);
	}
	bool IsLightmapName(const FString& Name)
	{
		return Name.Contains(TEXT("lightmap"), ESearchCase::CaseSensitive) || EndsWithLM(Name, false) ||
			Name.Contains(TEXT("LM_"), ESearchCase::CaseSensitive) || Name.Contains(TEXT("_LM"), ESearchCase::CaseSensitive);
	}
	bool IsNonColourName(const FString& Name)
	{
		static const TCHAR* const Words[] = { TEXT("mask"), TEXT("msk"), TEXT("spec"), TEXT("detail"), TEXT("opac"), TEXT("bump"), TEXT("normal"), TEXT("lightmap"), TEXT("shadow"), TEXT("lm_"), TEXT("_lm") };
		for (const TCHAR* W : Words)
		{
			if (Name.Contains(W, ESearchCase::IgnoreCase)) return true;
		}
		return EndsWithLM(Name, true);
	}

