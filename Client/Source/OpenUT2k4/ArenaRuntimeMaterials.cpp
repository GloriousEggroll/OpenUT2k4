	class FResolver
	{
	public:
		FResolution Resolve(const FString& Path)
		{
			FResolution R;
			R.Path = Path;
			const FNodePtr Top = Graph().Node(Path);
			if (Top.IsValid())
			{
				R.bFound = true;
				const FPickPtr Pick = Walk(Path, 0, TSet<FString>());
				Fill(R, Top, Pick);
			}
			return R;
		}

	private:
		double Penalty(const FPickPtr& Pick, ECombineOp Op, bool bHasOp)
		{
			if (!Pick.IsValid())
			{
				return 100.0;
			}
			const FNode& N = *Pick->Tex;
			const FString Name = N.LastName();
			double Pen = 0.0;
			bool bLightmap = IsLightmapName(Name);
			for (const FNodePtr& X : Pick->PathNodes)
			{
				bLightmap = bLightmap || IsLightmapName(X->LastName()) || X->Path.ToLower().Contains(TEXT("lightmap"));
			}
			if (bLightmap)
			{
				Pen += 3.0;
			}
			else if (IsNonColourName(Name))
			{
				Pen += 1.5;
			}
			if (Pick->Flags.Contains(TEXT("texgen")))
			{
				Pen += 1.0;
			}
			if (N.IsA(TEXT("Cubemap")) || Pick->Flags.Contains(TEXT("cubemap")))
			{
				Pen += 2.0;
			}
			const double* U = Pick->UV.V;
			if (FMath::Abs(U[0] * U[3] - U[1] * U[2]) < 1.0 / 64.0)
			{
				Pen += 1.0;
			}
			const TSharedPtr<FJsonObject> S = Graph().TexStats(N.Path);
			if (S.IsValid())
			{
				const double Lum = StatNum(S, TEXT("lum"), 0.5), Std = StatNum(S, TEXT("std"), 0.1);
				if (Lum < 0.06 || StatNum(S, TEXT("black"), 0.0) > 0.8)
				{
					Pen += (bHasOp && (Op == ECombineOp::Add || Op == ECombineOp::AddMaskMod)) ? 2.5 : 1.5;
				}
				if (Std < 0.015)
				{
					Pen += 1.0;
				}
				if (Lum > 0.9 && Std < 0.05)
				{
					Pen += 1.0;
				}
			}
			if (N.bProcedural)
			{
				Pen += 0.5;
			}
			return Pen;
		}

		static FPickPtr Through(const FNodePtr& N, FPickPtr Sub, std::initializer_list<const TCHAR*> Flags)
		{
			if (!Sub.IsValid())
			{
				return nullptr;
			}
			Sub->PathNodes.Insert(N, 0);
			for (const TCHAR* F : Flags)
			{
				Sub->Flags.Add(F);
			}
			return Sub;
		}

		FPickPtr Walk(const FString& Path, int32 Depth, const TSet<FString>& SeenIn)
		{
			FNodePtr N = Graph().Node(Path);
			if (N.IsValid() && N->bMaterial && SeenIn.Contains(N->Path.ToLower()))
			{
				N = Graph().Node(Path, true); // a reference to a same-named texture, not a cycle
			}
			if (!N.IsValid() || Depth > 24 || (N->bMaterial && SeenIn.Contains(N->Path.ToLower())))
			{
				return nullptr;
			}
			TSet<FString> Seen = SeenIn;
			Seen.Add(N->Path.ToLower());
			if (!N->bMaterial)
			{
				if (N->W == 0 && N->H == 0 && N->Png.IsEmpty())
				{
					return nullptr;
				}
				FPickPtr P = MakeShared<FPick>();
				P->Tex = N;
				P->PathNodes.Add(N);
				return P;
			}
			const FNode& Nd = *N;
			if (Nd.IsA(TEXT("Cubemap")))
			{
				const TSharedPtr<FJsonValue> Faces = Prop(Nd, TEXT("Faces"));
				TSharedPtr<FJsonValue> Face = Faces;
				if (Faces.IsValid() && Faces->Type == EJson::Array)
				{
					const TArray<TSharedPtr<FJsonValue>>& A = Faces->AsArray();
					Face = A.Num() > 0 ? A[0] : nullptr;
				}
				FPickPtr Sub = IsRef(Face) ? Walk(Face->AsString(), Depth + 1, Seen) : nullptr;
				if (!Sub.IsValid())
				{
					Sub = Walk(PropRef(Nd, TEXT("FallbackMaterial")), Depth + 1, Seen);
				}
				return Through(N, Sub, { TEXT("cubemap") });
			}
			if (Nd.IsA(TEXT("Shader")))
			{
				static const TCHAR* const Keys[] = { TEXT("Diffuse"), TEXT("SelfIllumination"), TEXT("FallbackMaterial"), TEXT("Specular"), TEXT("Opacity") };
				for (const TCHAR* Key : Keys)
				{
					if (FPickPtr Sub = Walk(PropRef(Nd, Key), Depth + 1, Seen))
					{
						return Through(N, Sub, {});
					}
				}
				return nullptr;
			}
			if (Nd.IsA(TEXT("Combiner")))
			{
				return Combiner(N, Depth, Seen);
			}
			if (Nd.IsA(TEXT("MaterialSwitch")))
			{
				TArray<TSharedPtr<FJsonValue>> Cand;
				const TSharedPtr<FJsonValue> Mats = Prop(Nd, TEXT("Materials"));
				const int32 Cur = int32(Num(Prop(Nd, TEXT("Current")), 0));
				if (Mats.IsValid() && Mats->Type == EJson::Array && Mats->AsArray().Num() > 0)
				{
					const TArray<TSharedPtr<FJsonValue>>& A = Mats->AsArray();
					Cand.Add(A.IsValidIndex(Cur) ? A[Cur] : A[0]);
					Cand.Append(A);
				}
				Cand.Add(Prop(Nd, TEXT("Material")));
				Cand.Add(Prop(Nd, TEXT("FallbackMaterial")));
				for (const TSharedPtr<FJsonValue>& C : Cand)
				{
					if (FPickPtr Sub = Walk(RefOf(C), Depth + 1, Seen))
					{
						return Through(N, Sub, {});
					}
				}
				return nullptr;
			}
			if (Nd.IsA(TEXT("MaterialSequence")))
			{
				TArray<TSharedPtr<FJsonValue>> Cand;
				const TSharedPtr<FJsonValue> Items = Prop(Nd, TEXT("SequenceItems"));
				if (Items.IsValid() && Items->Type == EJson::Array)
				{
					for (const TSharedPtr<FJsonValue>& It : Items->AsArray())
					{
						Cand.Add(It.IsValid() && It->Type == EJson::Object ? It->AsObject()->TryGetField(TEXT("Material")) : It);
					}
				}
				Cand.Add(Prop(Nd, TEXT("FallbackMaterial")));
				for (const TSharedPtr<FJsonValue>& C : Cand)
				{
					if (FPickPtr Sub = Walk(RefOf(C), Depth + 1, Seen))
					{
						return Through(N, Sub, {});
					}
				}
				return nullptr;
			}
			if (Nd.IsA(TEXT("Modifier")))
			{
				FPickPtr Sub = Walk(PropRef(Nd, TEXT("Material")), Depth + 1, Seen);
				if (!Sub.IsValid())
				{
					Sub = Walk(PropRef(Nd, TEXT("FallbackMaterial")), Depth + 1, Seen);
				}
				if (!Sub.IsValid())
				{
					return nullptr;
				}
				if (Nd.IsA(TEXT("TexModifier")))
				{
					bool bHasStep;
					FUV Step;
					FString Flag;
					ModifierUV(Nd, bHasStep, Step, Flag);
					if (!Flag.IsEmpty())
					{
						Sub->Flags.Add(Flag);
					}
					if (Nd.IsA(TEXT("TexEnvMap")))
					{
						Sub->Flags.Add(TEXT("envmap")); // (runtime only: BuildMaterial's reflection stand-in)
					}
					if (bHasStep)
					{
						Sub->UV = Compose(Step, Sub->UV);
					}
				}
				return Through(N, Sub, {});
			}
			// ConstantColor, FadeColor, VertexColor, ScriptedTexture...: no texture of their own
			FPickPtr Sub = Walk(PropRef(Nd, TEXT("FallbackMaterial")), Depth + 1, Seen);
			return Sub.IsValid() ? Through(N, Sub, { TEXT("fallback") }) : nullptr;
		}

		/** Linear RGB of a ConstantColor input or of a single-colour texture input (matresolve _flat_colour). */
		bool FlatColour(const FString& Ref, const FPickPtr& Pick, FVector3d& Out)
		{
			const FNodePtr N = Graph().Node(Ref);
			if (N.IsValid() && N->bMaterial && N->IsA(TEXT("ConstantColor")))
			{
				const TSharedPtr<FJsonValue> C = Prop(*N, TEXT("Color"));
				const TSharedPtr<FJsonObject> CO = C.IsValid() && C->Type == EJson::Object ? C->AsObject() : MakeShared<FJsonObject>();
				Out = FVector3d(SrgbToLinear(Num(CO->TryGetField(TEXT("R")), 0.0) / 255.0),
					SrgbToLinear(Num(CO->TryGetField(TEXT("G")), 0.0) / 255.0),
					SrgbToLinear(Num(CO->TryGetField(TEXT("B")), 0.0) / 255.0));
				return true;
			}
			if (!Pick.IsValid() || Pick->bHasTint)
			{
				return false;
			}
			const TSharedPtr<FJsonObject> S = Graph().TexStats(Pick->Tex->Path);
			const TArray<TSharedPtr<FJsonValue>>* Mean = nullptr;
			const double* U = Pick->UV.V;
			if (S.IsValid() && S->TryGetArrayField(TEXT("mean"), Mean) && Mean->Num() >= 3 && StatNum(S, TEXT("std"), 1.0) < 0.015 &&
				StatNum(S, TEXT("chroma"), 1.0) < 0.6 && FMath::Abs(U[0] * U[3] - U[1] * U[2]) > 1e-6)
			{
				Out = FVector3d(SrgbToLinear((*Mean)[0]->AsNumber()), SrgbToLinear((*Mean)[1]->AsNumber()), SrgbToLinear((*Mean)[2]->AsNumber()));
				return true;
			}
			return false;
		}

		FPickPtr ByPenalty(const FPickPtr& M1, const FPickPtr& M2, ECombineOp Op)
		{
			if (!M1.IsValid() || !M2.IsValid())
			{
				return M1.IsValid() ? M1 : M2;
			}
			return Penalty(M2, Op, true) < Penalty(M1, Op, true) ? M2 : M1;
		}

		/** Share of the surface showing Material2 for AlphaBlend_With_Mask; < 0 without statistics. */
		double MaskWeight(const FPickPtr& Mask, const FNode& N)
		{
			if (!Mask.IsValid())
			{
				return -1.0;
			}
			const TSharedPtr<FJsonObject> S = Graph().TexStats(Mask->Tex->Path);
			if (!S.IsValid() || S->Values.Num() == 0)
			{
				return -1.0;
			}
			double A = Truthy(S->TryGetField(TEXT("has_alpha"))) ? StatNum(S, TEXT("alpha"), 1.0) : StatNum(S, TEXT("lum"), 0.5);
			if (Truthy(Prop(N, TEXT("InvertMask"))))
			{
				A = 1.0 - A;
			}
			return A;
		}

		FPickPtr Combiner(const FNodePtr& NPtr, int32 Depth, const TSet<FString>& Seen)
		{
			const FNode& N = *NPtr;
			const ECombineOp Op = CombineOp(int32(Num(Prop(N, TEXT("CombineOperation")), 0)));
			FPickPtr M1 = Walk(PropRef(N, TEXT("Material1")), Depth + 1, Seen);
			FPickPtr M2 = Walk(PropRef(N, TEXT("Material2")), Depth + 1, Seen);
			const FString MaskRef = PropRef(N, TEXT("Mask"));
			FPickPtr Mask = MaskRef.IsEmpty() ? nullptr : Walk(MaskRef, Depth + 1, Seen);

			// baked by the converter: Add of two plain textures (team skins)
			const FNodePtr Baked = Graph().Node(N.Path + TEXT("_Baked"));
			if (Baked.IsValid() && !Baked->bMaterial && Baked->bBaked)
			{
				FPickPtr P = MakeShared<FPick>();
				P->Tex = Baked;
				P->PathNodes = { NPtr, Baked };
				P->Flags.Add(TEXT("baked"));
				return P;
			}

			// the author's single-texture fallback names the texture that matters
			const FString Fb = PropRef(N, TEXT("FallbackMaterial"));
			if (!Fb.IsEmpty() && (M1.IsValid() || M2.IsValid()))
			{
				if (FPickPtr F = Walk(Fb, Depth + 1, Seen))
				{
					for (const FPickPtr& M : { M1, M2 })
					{
						if (M.IsValid() && M->Tex->Path.Equals(F->Tex->Path, ESearchCase::IgnoreCase))
						{
							return Through(NPtr, M, {});
						}
					}
				}
			}

			FPickPtr Pick;
			switch (Op)
			{
			case ECombineOp::Material1: Pick = M1.IsValid() ? M1 : M2; break;
			case ECombineOp::Material2: Pick = M2.IsValid() ? M2 : M1; break;
			case ECombineOp::Mask: Pick = Mask.IsValid() ? Mask : M1; break;
			case ECombineOp::AlphaBlendMask:
			{
				const double W2 = MaskWeight(Mask, N);
				if (W2 < 0.0)
				{
					Pick = ByPenalty(M1, M2, Op);
				}
				else if (W2 >= 0.5)
				{
					Pick = M2.IsValid() ? M2 : M1;
				}
				else
				{
					Pick = M1.IsValid() ? M1 : M2;
				}
				// a lightmap / colour mask never wins over a real texture, whatever the coverage
				const FPickPtr Other = Pick == M2 ? M1 : M2;
				if (Pick.IsValid() && Other.IsValid() && Penalty(Pick, Op, true) >= Penalty(Other, Op, true) + 2.0)
				{
					Pick = Other;
				}
				break;
			}
			case ECombineOp::Multiply:
			{
				// a flat colour times a pattern: the pattern is the Base and the colour its Tint
				FVector3d C1, C2;
				const bool bC1 = FlatColour(PropRef(N, TEXT("Material1")), M1, C1);
				const bool bC2 = FlatColour(PropRef(N, TEXT("Material2")), M2, C2);
				if (bC2 && !bC1 && M1.IsValid())
				{
					Pick = M1;
					Pick->Tint = Pick->bHasTint ? Pick->Tint * C2 : C2;
					Pick->bHasTint = true;
				}
				else if (bC1 && !bC2 && M2.IsValid())
				{
					Pick = M2;
					Pick->Tint = Pick->bHasTint ? Pick->Tint * C1 : C1;
					Pick->bHasTint = true;
				}
				else
				{
					Pick = ByPenalty(M1, M2, Op);
				}
				break;
			}
			default: // add, add_mask_mod, subtract
				Pick = ByPenalty(M1, M2, Op);
				break;
			}
			if (!Pick.IsValid())
			{
				Pick = Walk(Fb, Depth + 1, Seen);
			}
			return Pick.IsValid() ? Through(NPtr, Pick, {}) : nullptr;
		}

		void ShaderExtras(FResolution& R, const FNode& N, const FPickPtr& Pick)
		{
			if (!Pick.IsValid() || R.bUnlit)
			{
				return;
			}
			const FString Base = Pick->Tex->Path;
			const FString SIRef = PropRef(N, TEXT("SelfIllumination"));
			if (!PropRef(N, TEXT("Diffuse")).IsEmpty() && !SIRef.IsEmpty())
			{
				const FPickPtr SI = Walk(SIRef, 0, TSet<FString>());
				const FString MaskRef = PropRef(N, TEXT("SelfIlluminationMask"));
				const FPickPtr Msk = MaskRef.IsEmpty() ? nullptr : Walk(MaskRef, 0, TSet<FString>());
				const bool bSame = SI.IsValid() && SI->Tex->Path.Equals(Base, ESearchCase::IgnoreCase);
				const bool bOpaqueSoFar = R.Blend.IsEmpty() || R.Blend == TEXT("opaque");
				if (Msk.IsValid() && Msk->Tex->Path.Equals(Base, ESearchCase::IgnoreCase) && Pick->Tex->bHasAlpha && bSame && bOpaqueSoFar)
				{
					R.EmissiveAlpha = 1.0; // glows where the diffuse alpha is set
				}
				else if (!Msk.IsValid() && bSame)
				{
					const TSharedPtr<FJsonObject> St = Graph().TexStats(Pick->Tex->Path);
					if (Pick->Tex->bHasAlpha && StatNum(St, TEXT("alpha"), 1.0) < 0.98 && bOpaqueSoFar)
					{
						R.EmissiveAlpha = 1.0; // the self-illumination's own alpha masks the glow
					}
					else
					{
						R.Emissive = 1.0; // the whole diffuse glows
					}
				}
			}
			if (!PropRef(N, TEXT("Specular")).IsEmpty() && !R.bHasSpec)
			{
				R.bHasSpec = true;
				R.Roughness = 0.5;
				R.Specular = 0.5;
			}
		}

		void Fill(FResolution& R, const FNodePtr& Top, const FPickPtr& Pick)
		{
			TArray<FNodePtr> Nodes;
			if (Pick.IsValid())
			{
				const FNode& T = *Pick->Tex;
				R.Base = T.Path;
				R.BasePng = !T.Png.IsEmpty() && FPaths::FileExists(T.Png) ? T.Png : FString();
				if (R.BasePng.IsEmpty())
				{
					R.Base.Reset();
				}
				R.UV = Pick->UV;
				R.bHasTint = Pick->bHasTint;
				R.Tint = Pick->Tint;
				R.Flags = Pick->Flags;
				Nodes = Pick->PathNodes;
			}
			else
			{
				Nodes.Add(Top);
			}
			// blend / sidedness / lighting along the chosen path (outermost decides, as in UE2). Below a Combiner
			// the material keeps the alpha flags of the exporter's original pick (its base_texture).
			bool bBelowCombiner = false;
			for (FNodePtr N : Nodes)
			{
				if (!N->bMaterial)
				{
					if (bBelowCombiner && Top->bMaterial)
					{
						FString Legacy, LegacyFile;
						if (Top->Doc->TryGetStringField(TEXT("base_texture_file"), LegacyFile) && !LegacyFile.IsEmpty() &&
							Top->Doc->TryGetStringField(TEXT("base_texture"), Legacy))
						{
							if (FNodePtr L = Graph().Node(Legacy, true))
							{
								N = L;
							}
						}
					}
					if (R.Blend.IsEmpty())
					{
						if (N->bMasked) R.Blend = TEXT("masked");
						else if (N->bAlphaTex) R.Blend = TEXT("translucent");
					}
					if (N->bTwoSided)
					{
						R.bTwoSided = true;
					}
					continue;
				}
				if (N->IsA(TEXT("Combiner")))
				{
					bBelowCombiner = true;
				}
				if (N->IsA(TEXT("Shader")))
				{
					const int32 OB = int32(Num(Prop(*N, TEXT("OutputBlending")), 0));
					if (R.Blend.IsEmpty())
					{
						R.Blend = ShaderBlend(OB);
						if (OB == 0 && !PropRef(*N, TEXT("Opacity")).IsEmpty())
						{
							R.Blend = TEXT("translucent");
						}
					}
					if (Truthy(Prop(*N, TEXT("TwoSided"))))
					{
						R.bTwoSided = true;
					}
					if (!PropRef(*N, TEXT("SelfIllumination")).IsEmpty() && PropRef(*N, TEXT("Diffuse")).IsEmpty())
					{
						R.bUnlit = true;
					}
					ShaderExtras(R, *N, Pick);
				}
				else if (N->IsA(TEXT("FinalBlend")))
				{
					const int32 FB = int32(Num(Prop(*N, TEXT("FrameBufferBlending")), 0));
					if (R.Blend.IsEmpty())
					{
						R.Blend = FrameBufferBlend(FB);
						if (R.Blend == TEXT("opaque") && Truthy(Prop(*N, TEXT("AlphaTest"))))
						{
							R.Blend = TEXT("masked");
						}
					}
					if (Truthy(Prop(*N, TEXT("TwoSided"))))
					{
						R.bTwoSided = true;
					}
				}
			}
			if (R.Blend.IsEmpty())
			{
				R.Blend = TEXT("opaque");
			}
			// modulate / additive surfaces ignore the lit-surface extras
			if (R.Blend != TEXT("opaque") && R.Blend != TEXT("masked") && R.Blend != TEXT("translucent"))
			{
				R.Emissive = R.EmissiveAlpha = 0.0;
				R.bHasSpec = false;
				R.Roughness = 0.8;
				R.Specular = 0.3;
			}
			if (R.bUnlit)
			{
				R.Emissive = R.EmissiveAlpha = 0.0;
			}
		}
	};

