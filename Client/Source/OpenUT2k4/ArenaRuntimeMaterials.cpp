	using FPickPtr = TSharedPtr<FPick>;

	FUV Matrix(const FNode& N, bool& bOk)
	{
		bOk = false;
		FUV O;
		const TSharedPtr<FJsonValue> M = Prop(N, TEXT("M"));
		if (!M.IsValid() || M->Type != EJson::Object)
		{
			return O;
		}
		const TSharedPtr<FJsonObject> MO = M->AsObject();
		const TSharedPtr<FJsonObject>* X = nullptr; const TSharedPtr<FJsonObject>* Y = nullptr; const TSharedPtr<FJsonObject>* Z = nullptr;
		if (!MO->TryGetObjectField(TEXT("XPlane"), X) || !MO->TryGetObjectField(TEXT("YPlane"), Y) || !MO->TryGetObjectField(TEXT("ZPlane"), Z))
		{
			return O;
		}
		const TSharedPtr<FJsonObject> P[3] = { *X, *Y, *Z };
		for (int32 i = 0; i < 3; ++i)
		{
			if (!P[i].IsValid() || !P[i]->HasField(TEXT("X")) || !P[i]->HasField(TEXT("Y")))
			{
				return O;
			}
			O.V[i * 2] = Num(P[i]->TryGetField(TEXT("X")), 0.0);
			O.V[i * 2 + 1] = Num(P[i]->TryGetField(TEXT("Y")), 0.0);
		}
		O.V[6] = O.V[7] = 0.0;
		bOk = true;
		return O;
	}

	/** UV step of one TexModifier (matresolve modifier_uv); bHasStep false when it has none. */
	void ModifierUV(const FNode& N, bool& bHasStep, FUV& Step, FString& Flag)
	{
		bHasStep = false;
		Flag.Reset();
		const int32 Tcs = int32(Num(Prop(N, TEXT("TexCoordSource")), TCS_NoChange));
		if (N.IsA(TEXT("TexEnvMap")) || (Tcs != TCS_NoChange && !(N.IsA(TEXT("TexPanner")) || N.IsA(TEXT("TexScaler")) || N.IsA(TEXT("TexRotator")) || N.IsA(TEXT("TexOscillator")))))
		{
			Flag = TEXT("texgen");
			return;
		}
		if (N.IsA(TEXT("TexScaler")))
		{
			bool bOk;
			Step = Matrix(N, bOk);
			if (!bOk)
			{
				double US = Num(Prop(N, TEXT("UScale")), 1.0); if (US == 0.0) US = 1.0;
				double VS = Num(Prop(N, TEXT("VScale")), 1.0); if (VS == 0.0) VS = 1.0;
				Step = FUV();
				Step.V[0] = 1.0 / US;
				Step.V[3] = 1.0 / VS;
			}
			bHasStep = true;
			return;
		}
		if (N.IsA(TEXT("TexPanner")))
		{
			const double Rate = Num(Prop(N, TEXT("PanRate")), 0.1);
			const TSharedPtr<FJsonValue> Rot = Prop(N, TEXT("PanDirection"));
			const TSharedPtr<FJsonObject> R = Rot.IsValid() && Rot->Type == EJson::Object ? Rot->AsObject() : nullptr;
			const double Yaw = (R.IsValid() ? Num(R->TryGetField(TEXT("Yaw")), 0.0) : 0.0) * 2.0 * UE_DOUBLE_PI / 65536.0;
			const double Pitch = (R.IsValid() ? Num(R->TryGetField(TEXT("Pitch")), 0.0) : 0.0) * 2.0 * UE_DOUBLE_PI / 65536.0;
			Step = FUV();
			Step.V[6] = Rate * FMath::Cos(Pitch) * FMath::Cos(Yaw);
			Step.V[7] = Rate * FMath::Cos(Pitch) * FMath::Sin(Yaw);
			bHasStep = true;
			return;
		}
		if (N.IsA(TEXT("TexRotator")))
		{
			if (int32(Num(Prop(N, TEXT("TexRotationType")), 0)) == 0)
			{
				bool bOk;
				Step = Matrix(N, bOk);
				if (bOk)
				{
					bHasStep = true;
					return;
				}
			}
			Flag = TEXT("rotating");
			return;
		}
		if (N.IsA(TEXT("TexOscillator")))
		{
			Flag = TEXT("oscillating");
		}
	}

	double SrgbToLinear(double C)
	{
		C = FMath::Clamp(C, 0.0, 1.0);
		return C <= 0.04045 ? C / 12.92 : FMath::Pow((C + 0.055) / 1.055, 2.4);
	}

