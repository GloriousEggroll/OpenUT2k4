	enum class ECombineOp { Material1, Material2, Multiply, Add, Subtract, AlphaBlendMask, AddMaskMod, Mask };
	ECombineOp CombineOp(int32 V)
	{
		switch (V)
		{
		case 1: return ECombineOp::Material2;
		case 2: return ECombineOp::Multiply;
		case 3: return ECombineOp::Add;
		case 4: return ECombineOp::Subtract;
		case 5: return ECombineOp::AlphaBlendMask;
		case 6: return ECombineOp::AddMaskMod;
		case 7: return ECombineOp::Mask;
		default: return ECombineOp::Material1;
		}
	}
	const TCHAR* ShaderBlend(int32 V)
	{
		static const TCHAR* const T[] = { TEXT("opaque"), TEXT("masked"), TEXT("modulate"), TEXT("additive"), TEXT("invisible"), TEXT("additive"), TEXT("modulate") };
		return V >= 0 && V < 7 ? T[V] : TEXT("opaque");
	}
	const TCHAR* FrameBufferBlend(int32 V)
	{
		static const TCHAR* const T[] = { TEXT("opaque"), TEXT("modulate"), TEXT("translucent"), TEXT("translucent"), TEXT("additive"), TEXT("modulate"), TEXT("additive"), TEXT("invisible") };
		return V >= 0 && V < 8 ? T[V] : TEXT("opaque");
	}
	constexpr int32 TCS_NoChange = 13;

	struct FUV
	{
		// a, b, c, d, e, f, pan u, pan v: u' = u a + v c + e, v' = u b + v d + f
		double V[8] = { 1, 0, 0, 1, 0, 0, 0, 0 };
		bool IsIdentity() const
		{
			static const double I[8] = { 1, 0, 0, 1, 0, 0, 0, 0 };
			for (int32 i = 0; i < 8; ++i) { if (FMath::Abs(V[i] - I[i]) > 1e-6) return false; }
			return true;
		}
	};

	/** Outer (the modifier's own step, applied first) then Inner (the transform below it); matresolve _compose(). */
	FUV Compose(const FUV& Outer, const FUV& Inner)
	{
		const double a = Outer.V[0], b = Outer.V[1], c = Outer.V[2], d = Outer.V[3], e = Outer.V[4], f = Outer.V[5], pu = Outer.V[6], pv = Outer.V[7];
		const double A = Inner.V[0], B = Inner.V[1], C = Inner.V[2], D = Inner.V[3], E = Inner.V[4], F = Inner.V[5], PU = Inner.V[6], PV = Inner.V[7];
		FUV O;
		O.V[0] = a * A + b * C; O.V[1] = a * B + b * D;
		O.V[2] = c * A + d * C; O.V[3] = c * B + d * D;
		O.V[4] = e * A + f * C + E; O.V[5] = e * B + f * D + F;
		O.V[6] = pu * A + pv * C + PU; O.V[7] = pu * B + pv * D + PV;
		return O;
	}

