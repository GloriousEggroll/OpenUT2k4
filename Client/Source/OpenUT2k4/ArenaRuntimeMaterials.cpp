	struct FNode
	{
		FString Path;
		bool bMaterial = false;
		FString Class;
		TArray<FString> Chain;
		TSharedPtr<FJsonObject> Props;
		TSharedPtr<FJsonObject> Doc;
		// textures
		FString Png;
		int32 W = 0, H = 0;
		bool bMasked = false, bAlphaTex = false, bTwoSided = false, bHasAlpha = false, bProcedural = false, bBaked = false;

		bool IsA(const TCHAR* Name) const { return Chain.Contains(Name); }
		FString LastName() const { int32 Dot; return Path.FindLastChar(TEXT('.'), Dot) ? Path.Mid(Dot + 1) : Path; }
	};
	using FNodePtr = TSharedPtr<const FNode, ESPMode::ThreadSafe>;

	bool IsRef(const TSharedPtr<FJsonValue>& V)
	{
		FString S;
		return V.IsValid() && V->Type == EJson::String && V->TryGetString(S) && !S.IsEmpty() && S != TEXT("None");
	}
	FString RefOf(const TSharedPtr<FJsonValue>& V) { return IsRef(V) ? V->AsString() : FString(); }
	TSharedPtr<FJsonValue> Prop(const FNode& N, const TCHAR* Key) { return N.Props.IsValid() ? N.Props->TryGetField(Key) : nullptr; }
	FString PropRef(const FNode& N, const TCHAR* Key) { return RefOf(Prop(N, Key)); }

	/** matresolve _num(): numbers, numeric strings and bools; Default otherwise. */
	double Num(const TSharedPtr<FJsonValue>& V, double Default)
	{
		if (!V.IsValid())
		{
			return Default;
		}
		switch (V->Type)
		{
		case EJson::Number: return V->AsNumber();
		case EJson::Boolean: return V->AsBool() ? 1.0 : 0.0;
		case EJson::String:
		{
			const FString S = V->AsString().TrimStartAndEnd();
			return !S.IsEmpty() && S.IsNumeric() ? FCString::Atod(*S) : Default;
		}
		default: return Default;
		}
	}
	bool Truthy(const TSharedPtr<FJsonValue>& V)
	{
		if (!V.IsValid()) return false;
		switch (V->Type)
		{
		case EJson::Boolean: return V->AsBool();
		case EJson::Number: return V->AsNumber() != 0.0;
		case EJson::String: return !V->AsString().IsEmpty();
		case EJson::Array: return V->AsArray().Num() > 0;
		case EJson::Object: return V->AsObject().IsValid() && V->AsObject()->Values.Num() > 0;
		default: return false;
		}
	}

	class FGraph
	{
	public:
		FNodePtr Node(const FString& Path, bool bTexture = false)
		{
			if (Path.IsEmpty() || Path == TEXT("None"))
			{
				return nullptr;
			}
			const FString Key = Path.ToLower() + (bTexture ? TEXT("#tex") : TEXT(""));
			{
				FScopeLock Lock(&Mutex);
				if (const FNodePtr* Found = Nodes.Find(Key))
				{
					return *Found;
				}
			}
			FNodePtr N = Read(Path, bTexture);
			FScopeLock Lock(&Mutex);
			Nodes.Add(Key, N);
			return N;
		}

		/** Statistics of a texture (matresolve tex_stats): the node's own "stats" or texture_stats.json. */
		TSharedPtr<FJsonObject> TexStats(const FString& Path)
		{
			const FNodePtr N = Node(Path);
			if (!N.IsValid())
			{
				return nullptr;
			}
			if (!N->bMaterial)
			{
				const TSharedPtr<FJsonObject>* S = nullptr;
				if (N->Doc->TryGetObjectField(TEXT("stats"), S) && S->IsValid() && (*S)->Values.Num() > 0)
				{
					return *S;
				}
			}
			const TSharedPtr<FJsonObject>* S = FindTextureStats(N->Path);
			return S ? *S : nullptr;
		}

		void Reset()
		{
			FScopeLock Lock(&Mutex);
			Nodes.Reset();
		}

	private:
		FNodePtr Read(const FString& Path, bool bTexture)
		{
			const FString MatFile = bTexture ? FString() : FindByObjectPath(TEXT("materials"), Path);
			const FString TexFile = FindByObjectPath(TEXT("textures"), Path);
			TSharedPtr<FNode, ESPMode::ThreadSafe> N = MakeShared<FNode, ESPMode::ThreadSafe>();
			if (!MatFile.IsEmpty())
			{
				N->Doc = LoadJson(MatFile + TEXT(".json"));
				if (!N->Doc.IsValid())
				{
					return nullptr;
				}
				N->bMaterial = true;
				if (!N->Doc->TryGetStringField(TEXT("path"), N->Path) || N->Path.IsEmpty()) N->Path = Path;
				N->Doc->TryGetStringField(TEXT("class"), N->Class);
				const TArray<TSharedPtr<FJsonValue>>* Chain = nullptr;
				if (N->Doc->TryGetArrayField(TEXT("class_chain"), Chain) && Chain->Num() > 0)
				{
					for (const TSharedPtr<FJsonValue>& C : *Chain) { N->Chain.Add(C->AsString()); }
				}
				else
				{
					N->Chain.Add(N->Class);
				}
				const TSharedPtr<FJsonObject>* P = nullptr;
				N->Props = N->Doc->TryGetObjectField(TEXT("properties"), P) && P->IsValid() ? *P : MakeShared<FJsonObject>();
				return N;
			}
			if (!TexFile.IsEmpty())
			{
				N->Doc = LoadJson(TexFile + TEXT(".json"));
				if (!N->Doc.IsValid())
				{
					return nullptr;
				}
				if (!N->Doc->TryGetStringField(TEXT("path"), N->Path) || N->Path.IsEmpty()) N->Path = Path;
				if (!N->Doc->TryGetStringField(TEXT("class"), N->Class) || N->Class.IsEmpty()) N->Class = TEXT("Texture");
				N->Chain = { N->Class, TEXT("Texture") };
				N->Props = MakeShared<FJsonObject>();
				FString PngName;
				if (N->Doc->TryGetStringField(TEXT("png"), PngName) && !PngName.IsEmpty())
				{
					N->Png = FPaths::GetPath(TexFile) / PngName;
				}
				N->W = int32(Num(N->Doc->TryGetField(TEXT("width")), 0));
				N->H = int32(Num(N->Doc->TryGetField(TEXT("height")), 0));
				N->bMasked = Truthy(N->Doc->TryGetField(TEXT("bMasked")));
				N->bAlphaTex = Truthy(N->Doc->TryGetField(TEXT("bAlphaTexture")));
				N->bTwoSided = Truthy(N->Doc->TryGetField(TEXT("bTwoSided")));
				N->bHasAlpha = Truthy(N->Doc->TryGetField(TEXT("has_alpha")));
				N->bProcedural = Truthy(N->Doc->TryGetField(TEXT("procedural_fallback")));
				N->bBaked = Truthy(N->Doc->TryGetField(TEXT("baked")));
				return N;
			}
			return nullptr;
		}

		FCriticalSection Mutex;
		TMap<FString, FNodePtr> Nodes;
	};

